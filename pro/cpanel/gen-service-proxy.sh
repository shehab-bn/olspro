#!/bin/bash
#############################################################################
#    OLS PRO - cPanel service (proxy) subdomains for OLS (ROADMAP G2).      #
#    GPLv3, see GPL.txt                                                     #
#############################################################################
# Emits OLS config so cpanel./webmail./whm./cpcalendars./cpcontacts./
# autodiscover./autoconfig.<domain> reach cpsrvd instead of the OLS welcome
# page, while /.well-known/ (AutoSSL DCV) is still served from the account
# docroot. See service-subdomains.md.
#
#   gen-service-proxy.sh server            server-level extProcessor blocks
#   gen-service-proxy.sh aliases DOMAIN    vhAliases value for one account
#   gen-service-proxy.sh rules             rewrite rules for the account vhost
#                                          (put inside vhost "rewrite { rules }")
# CPSRVD_HOST (default 127.0.0.1) and CPSRVD_TLS=1 (proxy to the SSL ports
# 2083/2087/2096/2080 instead of 2082/2086/2095/2079) are honoured.

set -u
CPSRVD_HOST="${CPSRVD_HOST:-127.0.0.1}"
CPSRVD_TLS="${CPSRVD_TLS:-0}"

# name  plain-port  ssl-port  host-prefixes
SERVICES='cpanel 2082 2083 cpanel
whm 2086 2087 whm
webmail 2095 2096 webmail
caldav 2079 2080 cpcalendars|cpcontacts
autodiscover 2082 2083 autodiscover|autoconfig'

emit_server()
{
    local name plain ssl prefixes port scheme
    echo "# --- OLS PRO: cpsrvd proxy backends (generated by gen-service-proxy.sh) ---"
    while read -r name plain ssl prefixes; do
        [ -n "$name" ] || continue
        port=$plain
        scheme=""
        if [ "$CPSRVD_TLS" = "1" ]; then
            port=$ssl
            scheme="https://"
        fi
        cat <<EOF
extProcessor cpsrvd_${name} {
  type                    proxy
  address                 ${scheme}${CPSRVD_HOST}:${port}
  maxConns                50
  pcKeepAliveTimeout      60
  initTimeout             60
  retryTimeout            0
  respBuffer              0
}

EOF
    done <<< "$SERVICES"
}

emit_aliases()
{
    local dom="$1" out="www.$1" name plain ssl prefixes p
    while read -r name plain ssl prefixes; do
        [ -n "$name" ] || continue
        for p in ${prefixes//|/ }; do
            out="$out, $p.$dom"
        done
    done <<< "$SERVICES"
    echo "$out"
}

emit_rules()
{
    local name plain ssl prefixes
    cat <<'EOF'
# --- OLS PRO: cPanel service subdomains -> cpsrvd (keep BEFORE app rules) ---
# AutoSSL / ACME DCV must hit the account docroot, never cpsrvd.
RewriteCond %{REQUEST_URI} ^/\.well-known/(acme-challenge|pki-validation|cpanel-dcv)/
RewriteRule ^ - [L]
# Microsoft/Thunderbird autodiscovery -> cpsrvd's autodiscover CGI.
RewriteCond %{HTTP_HOST} ^(autodiscover|autoconfig)\. [NC]
RewriteRule ^/?(?i:autodiscover/autodiscover\.xml|mail/config-v1\.1\.xml)$ http://cpsrvd_autodiscover/cgi-sys/autodiscover.cgi [P,L]
EOF
    while read -r name plain ssl prefixes; do
        [ -n "$name" ] || continue
        [ "$name" = "autodiscover" ] && continue
        cat <<EOF
RewriteCond %{HTTP_HOST} ^(${prefixes})\\. [NC]
RewriteRule ^/?(.*)\$ http://cpsrvd_${name}/\$1 [P,L]
EOF
    done <<< "$SERVICES"
}

case "${1:-}" in
    server)  emit_server ;;
    aliases) [ -n "${2:-}" ] || { echo "usage: $0 aliases DOMAIN" >&2; exit 2; }
             emit_aliases "$2" ;;
    rules)   emit_rules ;;
    *)       echo "usage: $0 server | aliases DOMAIN | rules" >&2; exit 2 ;;
esac
